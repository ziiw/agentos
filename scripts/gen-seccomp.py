#!/usr/bin/env python3
"""Makes src/seccomp_strict.rs: the syscalls of Docker's default seccomp profile
(moby/profiles, seccomp/default.json) that exist on x86_64 and aarch64, with
their numbers. That profile is an allowlist that a great deal of software has
run under for years, which is what `--seccomp strict` wants to be.

  curl -O https://raw.githubusercontent.com/moby/profiles/main/seccomp/default.json
  curl -O https://raw.githubusercontent.com/torvalds/linux/master/arch/x86/entry/syscalls/syscall_64.tbl
  curl -O https://raw.githubusercontent.com/torvalds/linux/master/include/uapi/asm-generic/unistd.h
  scripts/gen-seccomp.py default.json syscall_64.tbl unistd.h > src/seccomp_strict.rs

Only the unconditional names are taken (the ones Docker allows with no
argument check and no capability); the few it allows only with arguments
(socket, personality, clone) are written by hand in sandbox.rs. The numbers
come from the kernel's own tables (x86_64's syscall_64.tbl; aarch64 uses the
generic table), not from a libc crate, which lags behind the kernel and
leaves out calls glibc doesn't wrap (renameat on aarch64, say).
"""
import json
import re
import sys

profile, x86_tbl, generic_h = sys.argv[1:4]
d = json.load(open(profile))
names = set()
for block in d["syscalls"]:
    if block["action"] != "SCMP_ACT_ALLOW" or "args" in block:
        continue
    inc, exc = block.get("includes", {}), block.get("excludes", {})
    if inc.get("caps") or exc.get("caps"):
        continue  # needs a capability we don't have, or is for one we don't give
    if inc.get("arches") and not ({"amd64", "arm64"} & set(inc["arches"])):
        continue
    names.update(block["names"])

x86 = {}
for line in open(x86_tbl):
    m = re.match(r"^(\d+)\s+(common|64)\s+(\w+)", line)
    if m:
        x86[m.group(3)] = int(m.group(1))

generic = {}
text = open(generic_h).read()
for m in re.finditer(r"^#define __NR_(\w+)\s+(\d+)\s*$", text, re.M):
    generic[m.group(1)] = int(m.group(2))
base = {}
for m in re.finditer(r"^#define __NR3264_(\w+)\s+(\d+)\s*$", text, re.M):
    base[m.group(1)] = int(m.group(2))
    generic.setdefault(m.group(1), int(m.group(2)))
# Names that stand for one of those (newfstatat, fstat, mmap, and the 32-bit spellings): the same number.
for m in re.finditer(r"^#define __NR_(\w+)\s+__NR3264_(\w+)\s*$", text, re.M):
    if m.group(2) in base:
        generic.setdefault(m.group(1), base[m.group(2)])

print("// Generated by scripts/gen-seccomp.py from Docker's default seccomp profile (the")
print("// syscalls it allows without a condition) and the kernel's syscall tables: each")
print("// syscall's name and number on this architecture. Do not edit by hand.\n")
for cfg, table in (("x86_64", x86), ("aarch64", generic)):
    present = sorted((n, table[n]) for n in names if n in table)
    skipped = sorted(n for n in names if n not in table)
    print(f'#[cfg(target_arch = "{cfg}")]')
    print(f"/// {len(present)} syscalls. Docker allows these too, but this architecture has no such syscall (a 32-bit name, or another architecture's): {', '.join(skipped)}.")
    print("pub const STRICT: &[(&str, i64)] = &[")
    for n, num in present:
        print(f'    ("{n}", {num}),')
    print("];\n")
